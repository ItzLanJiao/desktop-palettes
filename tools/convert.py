"""Convert ccthemes (theme-gallery) palettes into desktop palettes: {id, name, base, bg, text, accent, ...extras}.

usage: python -I tools/convert.py <ccthemes themes dir> <out catalog.json> [hooks/palettes.ts]
The ccthemes palettes are in https://github.com/livlign/ccthemes under plugins/theme-gallery/themes.
"""
import json, sys, pathlib

# Canonical editor backgrounds for palettes that come from a well-known scheme
CANON = {
    'ayu-dark': '#0d1017', 'campbell': '#0c0c0c', 'catppuccin-mocha': '#1e1e2e', 'catppuccin-latte': '#eff1f5',
    'dracula': '#282a36', 'everforest': '#2d353b', 'github-dark': '#0d1117', 'github-light': '#ffffff',
    'gruvbox': '#282828', 'halcyon': '#1d2433', 'high-contrast': '#000000', 'horizon': '#1c1e26',
    'kanagawa': '#1f1f28', 'monokai-pro': '#2d2a2e', 'night-owl': '#011627', 'nord': '#2e3440',
    'one-dark': '#282c34', 'oxocarbon': '#161616', 'rose-pine': '#191724', 'rose-pine-dawn': '#faf4ed',
    'solarized-dark': '#002b36', 'solarized-light': '#fdf6e3', 'synthwave': '#262335', 'tokyo-night': '#1a1b26',
}

# Solarized body text one step stronger (base1 / base01), so the canonical background can stay
TEXT = {'solarized-dark': '#93a1a1', 'solarized-light': '#586e75'}

def rgb(h):
    h = h.strip().lstrip('#')
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    return [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]

def hx(c): return '#' + ''.join(f'{round(max(0, min(1, v)) * 255):02x}' for v in c)
def mix(a, b, k): return [x + (y - x) * k for x, y in zip(a, b)]
def lum(c):
    c = [v / 12.92 if v <= .03928 else ((v + .055) / 1.055) ** 2.4 for v in c]
    return .2126 * c[0] + .7152 * c[1] + .0722 * c[2]
def contrast(a, b):
    x, y = lum(a), lum(b)
    return (max(x, y) + .05) / (min(x, y) + .05)

BLACK, WHITE = [0, 0, 0], [1, 1, 1]

def convert(slug, t):
    o = t['overrides']
    dark = not t['base'].startswith('light')
    text_hex = TEXT.get(slug, o['text'])
    text, accent = rgb(text_hex), rgb(o['claude'])
    if slug in CANON:
        bg = rgb(CANON[slug])
    else:
        um = rgb(o.get('userMessageBackground', '#12141a' if dark else '#f4f4f6'))
        bg = mix(um, BLACK, .45) if dark else mix(um, WHITE, .55)
    # keep body text at 7:1 or better: push the background away from the text until it is
    toward = BLACK if dark else WHITE
    k = 0
    need = 4.5 if slug in CANON else 7
    while contrast(text, bg) < need and k < 1:
        k += .05
        bg = mix(bg, toward, .05 / max(.05, 1 - k + .05))
    out = {
        'id': slug, 'name': t['name'], 'base': 'dark' if dark else 'light',
        'bg': hx(bg), 'text': text_hex.lower(), 'accent': o['claude'].lower(),
    }
    for key in ('success', 'error', 'warning', 'userMessageBackground', 'diffAdded', 'diffRemoved', 'inactive', 'planMode'):
        if key in o: out[key] = o[key].lower()
    out['contrast'] = {'text': round(contrast(text, bg), 2), 'accent': round(contrast(accent, bg), 2)}
    return out

def main(src, dst):
    cat = [convert(p.stem, json.loads(p.read_text(encoding='utf-8'))) for p in sorted(pathlib.Path(src).glob('*.json'))]
    cat.sort(key=lambda t: (t['base'] != 'dark', t['name'].lower()))
    pathlib.Path(dst).write_text(json.dumps(cat, indent=1), encoding='utf-8')
    for t in cat:
        flag = '' if t['contrast']['text'] >= 7 and t['contrast']['accent'] >= 3 else '  <-- low'
        print(f"{t['id']:18} {t['base']:5} bg {t['bg']} text {t['contrast']['text']:5} accent {t['contrast']['accent']:5}{flag}")

KEYS = ('id', 'name', 'base', 'bg', 'text', 'accent', 'success', 'error', 'warning')

def write_ts(cat, dst):
    lines = ["// Generated by tools/convert.py from the ccthemes palettes (MIT, ccthemes contributors). Do not edit by hand.",
             "import type { Palette } from '../types'", "", "export const PALETTES: Palette[] = ["]
    lines += ['  ' + json.dumps({k: t[k] for k in KEYS if k in t}, separators=(', ', ': ')) + ',' for t in cat]
    pathlib.Path(dst).write_text(chr(10).join(lines + [']']) + chr(10), encoding='utf-8')

main(*sys.argv[1:3])
if len(sys.argv) > 3:
    write_ts(json.loads(pathlib.Path(sys.argv[2]).read_text(encoding='utf-8')), sys.argv[3])
